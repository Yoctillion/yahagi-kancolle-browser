#!/usr/bin/env python3
"""Generate lib/src/item_panel/use_item_strings.dart from a KC3Kai checkout.

Usage: python -I tool/generate_use_item_strings.py <path-to-KC3Kai/src>
Run `dart format lib/src/item_panel` afterwards.
"""

import json
import sys
from pathlib import Path

# Tuple order matches the resource records in fleet_ui_strings.dart.
LANGUAGES = ("scn", "tcn", "jp", "kr", "en")
TARGET = Path("lib/src/item_panel/use_item_strings.dart")


def load_names(source, language):
    path = source / "data" / "lang" / "data" / language / "useitems.json"
    # KC3 keeps these files with a UTF-8 BOM.
    return json.loads(path.read_text(encoding="utf-8-sig"))


def name_at(names, index):
    return names[index].strip() if index < len(names) else ""


def main(argv):
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    source = Path(argv[1])
    tables = {language: load_names(source, language) for language in LANGUAGES}
    fallback = tables["en"]
    lines = [
        "// Generated by tool/generate_use_item_strings.py from KC3Kai.",
        "// Do not edit by hand.",
        "",
        "const useItemStrings = <int, (String, String, String, String, String)>{",
    ]
    for index in range(max(len(table) for table in tables.values())):
        english = name_at(fallback, index)
        if not english and not name_at(tables["jp"], index):
            continue
        values = [
            name_at(tables[language], index) or english for language in LANGUAGES
        ]
        encoded = ", ".join(json.dumps(value, ensure_ascii=False) for value in values)
        lines.append(f"  {index}: ({encoded}),")
    lines.append("};")
    TARGET.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
